# Builds js/fooddb.js from USDA FNDDS (Survey) bulk JSON + tools/fooddb/foods.txt.
# Usage: python3 tools/fooddb/build.py /path/to/surveyDownload.json
import json, re, sys
src = json.load(open(sys.argv[1]))['SurveyFoods']
N = {'208': 'kcal', '203': 'p', '205': 'c', '204': 'f'}
def toks(s): return re.findall(r"[a-z0-9&%']+", s.lower())
ODD = {'stuffed','glutinous','greens','diet','baby','infant','toddler','frozen','canned','light','reduced','free','low','dry','mix','powder','dehydrated','imitation','ingredient','extra','thin','fruit','sandwich','with','made','fast','no cheese','restaurant'}
idx = []
for food in src:
    d = food['description']; t = toks(d)
    nut = {}
    for n in food.get('foodNutrients', []):
        k = N.get(str(n.get('nutrient', {}).get('number')))
        if k: nut[k] = round(n.get('amount', 0), 1)
    if 'kcal' not in nut: continue
    por = [(p.get('portionDescription', ''), p.get('gramWeight', 0)) for p in food.get('foodPortions', [])]
    idx.append((d, set(t), t, nut, por, food['fdcId']))
def best(q):
    qt = toks(q); cands = []
    for d, ts, t, nut, por, fid in idx:
        if all(any(w == x or w + 's' == x or x + 's' == w or w + 'es' == x for x in ts) for w in qt):
            odd = sum(1 for x in ts if x in ODD and x not in qt)
            dl = d.lower(); s = -len(t) + (6 if 'nfs' in ts else 0) + (8 if 'no added fat' in dl or ', plain' in dl else 0) - (9 if re.search(r'\bno (cheese|meat|sauce)', dl) else 0) + (3 if t and t[0].rstrip('s') == qt[0].rstrip('s') else 0) - 5 * odd
            cands.append((s, d, nut, por, fid))
    return max(cands, key=lambda c: c[0]) if cands else None
out, miss = [], []
for line in open(sys.argv[2] if len(sys.argv) > 2 else 'tools/fooddb/foods.txt'):
    line = line.strip()
    if not line or line.startswith('#'): continue
    name, q, al = (line.split('|') + ['', ''])[:3]
    m = best(q or name) or best(name)
    if not m: miss.append(name); continue
    _, d, nut, por, fid = m
    nt = [w.rstrip('s') for w in toks(name) if len(w) > 2]
    sv = [(re.sub(r'\s+', ' ', a).strip(), round(g, 1)) for a, g in por if g and a and 'not specified' not in a.lower()]
    def sk(x):
        l, g = x[0].lower(), x[1]
        return -(2 * any(w in l for w in nt) + 3 * (30 <= g <= 450) + ('medium' in l) + ('piece' in l or 'slice' in l and g > 30) - 3 * ('extra' in l) - 2 * ('fl oz' in l and 'ice' in l) - 2 * (g < 15))
    sv = sorted(sv, key=sk)[:4]
    if not sv:
        sv = [(a or 'serving', round(g, 1)) for a, g in por if g][:1] or [('100 g', 100)]
    out.append({'n': name, 'a': [x.strip() for x in al.split(',') if x.strip()], 'u': d, 'id': fid,
                'k': nut.get('kcal', 0), 'p': nut.get('p', 0), 'c': nut.get('c', 0), 'f': nut.get('f', 0), 's': sv})
seen, uniq = set(), []
for o in out:
    if o['n'].lower() in seen: continue
    seen.add(o['n'].lower()); uniq.append(o)
open('js/fooddb.js', 'w').write('// Generated by tools/fooddb/build.py from USDA FoodData Central FNDDS (Survey) 2024-10-31. Public domain (USDA).\n'
    '// Per food: n=name a=aliases u=USDA description id=fdcId k,p,c,f per 100 g; s=[[serving label, grams]].\n'
    'export const FOODDB=' + json.dumps(uniq, separators=(',', ':')) + ';\n')
print(len(uniq), 'foods; missing', len(miss)); print('MISS:', miss)
